# ============================================================
# 🏗 组装
# ============================================================
def build_system_prompt(state: dict, memory: Optional[list[str]] = None) -> str:
    parts = [
        DM_IDENTITY,
        WORLD_DND,
        NPC_DND,
        CHAPTER_GUIDE,
        TRUST_SYSTEM,
        EVENT_SYSTEM,
        _build_state(state),
    ]
    if memory:
        parts.append(_build_memory(memory))
    parts.append(TOOL_GUIDE)
    parts.append(STATE_DIRECTIVE_SYSTEM)
    parts.append(OUTPUT_DND)
    return "\n\n".join(parts)
